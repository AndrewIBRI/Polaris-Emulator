#!/bin/bash
# Polaris hotel runtime entrypoint.
# Generates config.ini + the Octane client configuration from env vars,
# then starts nginx and the emulator.
set -euo pipefail

DOMAIN="${APP_DOMAIN:-localhost}"
DOMAIN="${DOMAIN#https://}"; DOMAIN="${DOMAIN#http://}"
SCHEME="${APP_SCHEME:-https}"
BASE="${SCHEME}://${DOMAIN}"

DB_HOST="${DB_HOST:-polaris-db}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-polaris}"
DB_USER="${DB_USER:-polaris}"
DB_PASS="${DB_PASSWORD:?DB_PASSWORD is required}"
JAVA_XMX="${JAVA_XMX:-3072m}"

echo "[entrypoint] domain=${DOMAIN} db=${DB_HOST}:${DB_PORT}/${DB_NAME}"

mkdir -p /data/configuration /data/imager/badges /data/imager/camera/thumbnails /data/backups/database /data/logs

# ------------------------------------------------------------------ config.ini
cat > /data/config.ini <<EOF
# Generated by the container entrypoint — edit env vars instead of this file.
db.hostname=${DB_HOST}
db.port=${DB_PORT}
db.database=${DB_NAME}
db.username=${DB_USER}
db.password=${DB_PASS}
db.migrate.on_startup=true
db.migrations.backup.enabled=true
db.migrations.backup.directory=/data/backups/database
db.migrations.backup.executable=mariadb-dump
db.migrations.backup.keep=7
db.pool.minsize=25
db.pool.maxsize=100
db.integrity.audit.mode=warn

game.host=0.0.0.0
game.port=3000

rcon.host=127.0.0.1
rcon.port=3001
rcon.allowed=127.0.0.1

cms.api.enabled=false
cms.api.allowed=127.0.0.1

ws.enabled=true
ws.host=0.0.0.0
ws.port=2096
# Aceita conexão por qualquer domínio (configs/origem são dinâmicos por Host;
# a autenticação real é o ticket SSO — a whitelist não é o controle de acesso).
ws.whitelist=*
ws.ip.header=X-Forwarded-For
ws.ip.header.trusted=127.0.0.1

nitro.secure.assets.enabled=false
nitro.secure.api.enabled=false

login.remember.enabled=true
login.remember.cookie.samesite=Strict
login.remember.cookie.secure=true

imager.internal.enabled=true
imager.location.badgeparts=/var/www/gamedata/badgeparts
imager.location.output.badges=/data/imager/badges
imager.location.output.camera=/data/imager/camera
imager.location.output.thumbnail=/data/imager/camera/thumbnails

# Octane renders photos client-side and uploads the PNG; server-side rendering
# needs a full nitro render pipeline, so keep the client upload mode.
camera.render.mode=upload
# Furni rotations read from the furniture nitro bundles in the image
furni.directions.assets_dir=/opt/assets/bundled/furniture

system.log.debug=false
system.log.packets=false
EOF

# ------------------------------------------------------------------ voice (LiveKit)
# Public URL is always the hotel domain via the nginx /livekit proxy. The shared
# API secret is generated on first boot and persisted so the LiveKit server
# container can be (re)created with the same key.
LIVEKIT_API_KEY="${LIVEKIT_API_KEY:-polaris}"
if [ -z "${LIVEKIT_API_SECRET:-}" ]; then
  if [ ! -s /data/secrets/livekit-api-secret ]; then
    mkdir -p /data/secrets
    LIVEKIT_API_SECRET="$(head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 48)"
    printf '%s' "${LIVEKIT_API_SECRET}" > /data/secrets/livekit-api-secret
    chmod 600 /data/secrets/livekit-api-secret
  else
    LIVEKIT_API_SECRET="$(cat /data/secrets/livekit-api-secret)"
  fi
fi
cat >> /data/config.ini <<EOF

# Voice (LiveKit self-hosted, docs/PLANO-VOZ-CAMERA.md)
voice.livekit.url=wss://${DOMAIN}/livekit
voice.livekit.api_key=${LIVEKIT_API_KEY}
voice.livekit.api_secret=${LIVEKIT_API_SECRET}
EOF
echo "[entrypoint] voice livekit: key=${LIVEKIT_API_KEY} url=wss://${DOMAIN}/livekit"

# ---------------------------------------------- emulator_settings sync (pre-boot)
# The emulator's emulator_settings table OVERRIDES config.ini (loadFromDatabase
# runs after the ini load). A previous boot can write defaults back over the
# deployment values, so force the managed settings on every boot, before the
# emulator reads the table.
if command -v mariadb >/dev/null 2>&1; then
  SYNC_SQL="INSERT INTO emulator_settings (\`key\`, \`value\`) VALUES
    ('camera.render.mode','upload'),
    ('furni.directions.enabled','1'),
    ('furni.directions.assets_dir','/opt/assets/bundled/furniture'),
    ('imager.location.badgeparts','/var/www/gamedata/badgeparts'),
    ('imager.location.output.badges','/data/imager/badges'),
    ('imager.location.output.camera','/data/imager/camera'),
    ('imager.location.output.thumbnail','/data/imager/camera/thumbnails'),
    ('items.furnidata.path','/opt/assets/gamedata/FurnitureData.json')
  ON DUPLICATE KEY UPDATE \`value\`=VALUES(\`value\`);"
  _synced=0
  _err=""
  for _ in $(seq 1 15); do
    _err="$(mariadb -h"${DB_HOST}" -P"${DB_PORT}" -u"${DB_USER}" -p"${DB_PASS}" "${DB_NAME}" -e "${SYNC_SQL}" 2>&1 || true)"
    if [ -z "${_err}" ]; then
      echo "[entrypoint] emulator_settings synced (8 keys)"
      _synced=1
      break
    fi
    if echo "${_err}" | grep -q "doesn't exist"; then
      echo "[entrypoint] emulator_settings table missing (first boot); migrations will create it"
      break
    fi
    sleep 2
  done
  if [ "${_synced}" -eq 0 ] && [ -n "${_err}" ]; then
    echo "[entrypoint] WARN: emulator_settings sync failed: ${_err}"
  fi
else
  echo "[entrypoint] WARN: mariadb client not found; skipping emulator_settings sync"
fi

# ------------------------------------------------- Octane client configuration
# The baked copies from dist/ stay in place (pets.json, asset-loader.js, ...);
# the domain-dependent files are (re)generated on every boot.
cp -n /opt/dist/configuration/* /data/configuration/ 2>/dev/null || true

# Domain-dynamic configs: o arquivo guarda o marcador {{DOMAIN}} literal e o
# NGINX o substitui pelo Host da requisição (sub_filter) ao servir. Qualquer
# domínio apontado pro hotel recebe configs em same-origin, sem APP_DOMAIN fixo.
cp /opt/templates/renderer-config.json /data/configuration/renderer-config.json
cp /opt/templates/ui-config.json /data/configuration/ui-config.json

cat > /data/configuration/client-mode.json <<EOF
{
    "distObfuscationEnabled": false,
    "secureAssetsEnabled": false,
    "secureApiEnabled": false,
    "apiBaseUrl": "",
    "plainConfigBaseUrl": "",
    "plainGamedataBaseUrl": ""
}
EOF

# ------------------------------------------------------------- nginx + emulator
nginx -t
nginx

echo "[entrypoint] nginx up on :8080 — starting Polaris (heap ${JAVA_XMX})"
cd /data
exec java -Xmx"${JAVA_XMX}" -XX:+UseG1GC -jar /opt/polaris.jar
